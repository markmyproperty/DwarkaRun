    required this.nearBand,
    required this.postcard,
    required this.buildings,
    required this.monuments,
    required this.wild,
    required this.kerb,
    this.buildingWidth = 7.0,
    this.buildingChance = 0.62,
    this.gapWild = const [],
    this.extra = const [],
    this.obstacleArt = const {},
